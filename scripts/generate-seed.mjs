// Builds supabase/seed.sql from data/tours.json (the tours migrated from WordPress).
// Run: node scripts/generate-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const tours = JSON.parse(readFileSync(new URL("../data/tours.json", import.meta.url), "utf8"));
const q = (s) => `'${String(s ?? "").replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;

const rows = tours.map((t, i) => `(
  ${q(t.slug)}, ${q(t.title)}, ${q(t.duration)}, ${q(t.summary)}, ${q(t.price)}, ${q(t.itineraryTitle)},
  ${q(t.image)}, ${q(t.imageAlt)}, ${q(t.hero.src)}, ${q(t.hero.alt)},
  ${q(JSON.stringify(t.days))}::jsonb,
  ${arr(t.includes)}, ${arr(t.excludes)}, ${arr(t.notes)},
  ${arr(t.highlights ?? [])}, ${arr(t.categories ?? [])}, ${q(t.seoTitle)}, ${q(t.seoDescription)}, ${q(JSON.stringify(t.ja ?? {}))}::jsonb,
  true, ${(i + 1) * 10}
)`);

const sql = `-- Generated by scripts/generate-seed.mjs from data/tours.json. Safe to re-run.
insert into public.tours
  (slug, title, duration, summary, price, itinerary_title, image, image_alt, hero_image, hero_alt,
   days, includes, excludes, notes, highlights, categories, seo_title, seo_description, ja, published, sort_order)
values
${rows.join(",\n")}
on conflict (slug) do nothing;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote ${tours.length} tours to supabase/seed.sql`);
